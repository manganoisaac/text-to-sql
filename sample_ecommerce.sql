-- Retail / e-commerce training database for PostgreSQL and Text-to-SQL.
-- Load into a fresh database, for example:
--   createdb text2sql_sample
--   psql -v ON_ERROR_STOP=1 -d text2sql_sample -f sample_ecommerce.sql
--
-- This script intentionally creates a new schema and does not drop existing data.

\set ON_ERROR_STOP on

BEGIN;

CREATE SCHEMA retail;
SET search_path TO retail, public;

CREATE TABLE customers (
    customer_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name TEXT NOT NULL,
    last_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    phone TEXT,
    segment TEXT NOT NULL CHECK (segment IN ('consumer', 'small_business', 'enterprise')),
    signup_date DATE NOT NULL,
    marketing_opt_in BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE customer_addresses (
    address_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    label TEXT NOT NULL,
    line_1 TEXT NOT NULL,
    city TEXT NOT NULL,
    state_region TEXT NOT NULL,
    postal_code TEXT NOT NULL,
    country_code CHAR(2) NOT NULL,
    is_default BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX one_default_address_per_customer
    ON customer_addresses(customer_id) WHERE is_default;

CREATE TABLE suppliers (
    supplier_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_name TEXT NOT NULL UNIQUE,
    country_code CHAR(2) NOT NULL,
    contact_email TEXT NOT NULL,
    lead_time_days INTEGER NOT NULL CHECK (lead_time_days > 0),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE categories (
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE,
    parent_category_id BIGINT REFERENCES categories(category_id)
);

CREATE TABLE products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku TEXT NOT NULL UNIQUE,
    product_name TEXT NOT NULL,
    category_id BIGINT NOT NULL REFERENCES categories(category_id),
    list_price NUMERIC(10,2) NOT NULL CHECK (list_price >= 0),
    unit_cost NUMERIC(10,2) NOT NULL CHECK (unit_cost >= 0),
    weight_kg NUMERIC(8,3) NOT NULL CHECK (weight_kg >= 0),
    discontinued BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE product_suppliers (
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    supplier_id BIGINT NOT NULL REFERENCES suppliers(supplier_id),
    supplier_sku TEXT NOT NULL,
    supplier_cost NUMERIC(10,2) NOT NULL CHECK (supplier_cost >= 0),
    is_preferred BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (product_id, supplier_id)
);

CREATE TABLE warehouses (
    warehouse_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_name TEXT NOT NULL UNIQUE,
    city TEXT NOT NULL,
    state_region TEXT NOT NULL,
    country_code CHAR(2) NOT NULL
);

CREATE TABLE inventory (
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(warehouse_id),
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    on_hand INTEGER NOT NULL CHECK (on_hand >= 0),
    reserved INTEGER NOT NULL CHECK (reserved >= 0 AND reserved <= on_hand),
    reorder_point INTEGER NOT NULL CHECK (reorder_point >= 0),
    last_counted_at DATE NOT NULL,
    PRIMARY KEY (warehouse_id, product_id)
);

CREATE TABLE inventory_adjustments (
    adjustment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity_change INTEGER NOT NULL CHECK (quantity_change <> 0),
    reason TEXT NOT NULL CHECK (reason IN ('receipt', 'cycle_count', 'damage', 'transfer', 'return')),
    occurred_at TIMESTAMPTZ NOT NULL,
    note TEXT,
    FOREIGN KEY (warehouse_id, product_id) REFERENCES inventory(warehouse_id, product_id)
);

CREATE TABLE promotions (
    promotion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    promo_code TEXT NOT NULL UNIQUE,
    description TEXT NOT NULL,
    discount_pct NUMERIC(5,4) NOT NULL CHECK (discount_pct > 0 AND discount_pct <= 1),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    CHECK (ends_on >= starts_on)
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    ship_to_address_id BIGINT NOT NULL REFERENCES customer_addresses(address_id),
    ordered_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('pending', 'processing', 'shipped', 'delivered', 'cancelled')),
    sales_channel TEXT NOT NULL CHECK (sales_channel IN ('web', 'mobile_app', 'marketplace', 'phone')),
    currency CHAR(3) NOT NULL DEFAULT 'AUD'
);

CREATE TABLE order_items (
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    line_number SMALLINT NOT NULL CHECK (line_number > 0),
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    discount_pct NUMERIC(5,4) NOT NULL DEFAULT 0 CHECK (discount_pct >= 0 AND discount_pct <= 1),
    tax_rate NUMERIC(5,4) NOT NULL DEFAULT 0.10 CHECK (tax_rate >= 0 AND tax_rate <= 1),
    PRIMARY KEY (order_id, line_number)
);

CREATE TABLE order_promotions (
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    promotion_id BIGINT NOT NULL REFERENCES promotions(promotion_id),
    PRIMARY KEY (order_id, promotion_id)
);

CREATE TABLE payments (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    paid_at TIMESTAMPTZ NOT NULL,
    method TEXT NOT NULL CHECK (method IN ('card', 'paypal', 'bank_transfer', 'gift_card')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    status TEXT NOT NULL CHECK (status IN ('authorized', 'captured', 'failed', 'refunded')),
    provider_reference TEXT NOT NULL UNIQUE
);

CREATE TABLE shipments (
    shipment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouses(warehouse_id),
    carrier TEXT NOT NULL,
    tracking_number TEXT NOT NULL UNIQUE,
    shipped_at TIMESTAMPTZ NOT NULL,
    delivered_at TIMESTAMPTZ,
    status TEXT NOT NULL CHECK (status IN ('in_transit', 'delivered', 'exception')),
    UNIQUE (shipment_id, order_id),
    CHECK (delivered_at IS NULL OR delivered_at >= shipped_at)
);

CREATE TABLE shipment_items (
    shipment_id BIGINT NOT NULL,
    order_id BIGINT NOT NULL,
    line_number SMALLINT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    PRIMARY KEY (shipment_id, line_number),
    FOREIGN KEY (shipment_id, order_id) REFERENCES shipments(shipment_id, order_id),
    FOREIGN KEY (order_id, line_number) REFERENCES order_items(order_id, line_number)
);
CREATE UNIQUE INDEX one_shipment_per_order ON shipments(order_id);

CREATE TABLE return_requests (
    return_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    requested_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL CHECK (status IN ('requested', 'approved', 'received', 'rejected', 'refunded')),
    reason TEXT NOT NULL CHECK (reason IN ('damaged', 'wrong_item', 'not_as_described', 'changed_mind', 'other')),
    resolution TEXT,
    UNIQUE (return_id, order_id)
);

CREATE TABLE return_items (
    return_id BIGINT NOT NULL REFERENCES return_requests(return_id),
    order_id BIGINT NOT NULL,
    line_number SMALLINT NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    refund_amount NUMERIC(10,2) NOT NULL CHECK (refund_amount >= 0),
    PRIMARY KEY (return_id, line_number),
    FOREIGN KEY (return_id, order_id) REFERENCES return_requests(return_id, order_id),
    FOREIGN KEY (order_id, line_number) REFERENCES order_items(order_id, line_number)
);

CREATE TABLE product_reviews (
    review_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id),
    product_id BIGINT NOT NULL REFERENCES products(product_id),
    order_id BIGINT REFERENCES orders(order_id),
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    review_title TEXT NOT NULL,
    review_body TEXT NOT NULL,
    reviewed_at DATE NOT NULL,
    verified_purchase BOOLEAN NOT NULL DEFAULT FALSE
);

