CREATE VIEW order_totals AS
SELECT o.order_id,
       o.order_number,
       o.customer_id,
       o.ordered_at,
       o.status,
       sum(oi.quantity * oi.unit_price)::NUMERIC(12,2) AS subtotal,
       sum(oi.quantity * oi.unit_price * oi.discount_pct)::NUMERIC(12,2) AS line_discounts,
       sum(oi.quantity * oi.unit_price * (1 - oi.discount_pct) * oi.tax_rate)::NUMERIC(12,2) AS tax,
       sum(oi.quantity * oi.unit_price * (1 - oi.discount_pct) * (1 + oi.tax_rate))::NUMERIC(12,2) AS total
FROM orders o JOIN order_items oi USING (order_id)
GROUP BY o.order_id;

CREATE VIEW monthly_sales AS
SELECT date_trunc('month', o.ordered_at)::DATE AS sales_month,
       p.category_id,
       c.category_name,
       count(DISTINCT o.order_id) AS order_count,
       sum(oi.quantity) AS units_sold,
       sum(oi.quantity * oi.unit_price * (1 - oi.discount_pct))::NUMERIC(14,2) AS net_sales_before_tax
FROM orders o
JOIN order_items oi USING (order_id)
JOIN products p USING (product_id)
JOIN categories c USING (category_id)
WHERE o.status IN ('shipped', 'delivered')
GROUP BY 1, 2, 3;

CREATE VIEW customer_summary AS
SELECT c.customer_id,
       c.first_name,
       c.last_name,
       c.segment,
       count(DISTINCT o.order_id) FILTER (WHERE o.status <> 'cancelled') AS completed_or_open_orders,
       coalesce(sum(ot.total) FILTER (WHERE o.status IN ('shipped', 'delivered')), 0)::NUMERIC(14,2) AS fulfilled_order_value,
       max(o.ordered_at) AS most_recent_order_at
FROM customers c
LEFT JOIN orders o USING (customer_id)
LEFT JOIN order_totals ot USING (order_id)
GROUP BY c.customer_id;

